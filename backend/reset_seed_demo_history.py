"""
Reset ALL vitals history and reseed it with a curated demonstration dataset
for the demo patient (Yussif Hamza, hamza@rpm.com / PatientPass123).

The readings tell a staged clinical story so the kept file + app show the
FULL risk range:
  Phase 1  LOW      - weeks of normal vitals (diabetes/hypertension LOW)
  Phase 2  MODERATE - glucose & BP drift upward
  Phase 3  HIGH     - sustained elevated glucose/pressure
  Phase 4  CRITICAL - severe readings, sustained
  Phase 5  RECOVERY - post-intervention improvement back to MODERATE

Each reading goes through the REAL pipeline (VitalsService.record_reading),
so predictions, reasons, recommendations, alerts and notifications are all
authentically generated by the same code the running app uses.

Output files written to <repo>/demo-data/:
  demo_vitals_history.csv  - chronological table with per-condition risk
  demo_vitals_history.md   - presentation-ready summary
"""

