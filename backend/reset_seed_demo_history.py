SRC = {s.value if hasattr(s, "value") else s: VitalSource(s) for s in [VitalSource.MANUAL, VitalSource.DEVICE, VitalSource.CLINIC]}


def risk_cell(level: RiskLevel, score: float) -> str:
    return f"{level.value} ({score:.3f})"


def main():
    repo_root = Path(__file__).resolve().parent.parent
    out_dir = repo_root / "demo-data"
    out_dir.mkdir(exist_ok=True)

    db = SessionLocal()
    try:
        patients = db.query(PatientProfile).all()
        if not patients:
            print("No patient profiles found — nothing to do.")
            return
        for p in patients:
            db.query(Notification).filter(Notification.user_id == p.user_id).delete(synchronize_session=False)
            db.query(Alert).filter(Alert.patient_id == p.id).delete(synchronize_session=False)
            db.query(RiskPrediction).filter(RiskPrediction.patient_id == p.id).delete(synchronize_session=False)
            db.query(VitalReading).filter(VitalReading.patient_id == p.id).delete(synchronize_session=False)
        db.commit()

        svc = VitalsService(db)
        now = datetime.now(timezone.utc)

        rows = []
        for (days_ago, source, sys_, dia, hr, glu, ped, bmi, spo2, temp, rr, weight, note) in READINGS:
            result = svc.record_reading(
                patients[0].id,
                VitalReadingCreate(
                    recorded_at=now - timedelta(days=days_ago),
                    source=SRC[source],
                    conditions=ALL_CONDITIONS,
                    blood_pressure_systolic=sys_,
                    blood_pressure_diastolic=dia,
                    heart_rate_bpm=hr,
                    blood_glucose_mg_dl=glu,
                    diabetes_pedigree_function=ped,
                    bmi=bmi,
                    spo2_percent=spo2,
                    temperature_celsius=temp,
                    respiratory_rate=rr,
                    weight_kg=weight,
                    notes=note,
                ),
            )
            preds = {p.disease_type: p for p in result.predictions}
            rows.append(
                {
                    "recorded_at": result.vital.recorded_at,
                    "source": result.vital.source.value,
                    "sys": sys_, "dia": dia, "hr": hr, "glu": glu,
                    "bmi": bmi, "spo2": spo2, "temp": temp, "rr": rr, "weight": weight,
                    "notes": note,
                    "diabetes": preds.get(DIABETES),
                    "hypertension": preds.get(HYPERTENSION),
                    "stroke": preds.get(STROKE),
                }
            )
            lvl = lambda p: p.risk_level.value if p else "-"
            print(f"  {result.vital.recorded_at.strftime('%Y-%m-%d')}  sys {sys_:>3} glu {glu:>5.1f}  "
                  f"diab {lvl(preds.get(DIABETES)):>8} hype {lvl(preds.get(HYPERTENSION)):>8} stroke {lvl(preds.get(STROKE)):>8}")

        # --- Write the kept files -----------------------------------------------------------------
        csv_path = out_dir / "demo_vitals_history.csv"
        with open(csv_path, "w", newline="", encoding="utf-8-sig") as f:
            import csv as _csv
            w = _csv.writer(f)
            w.writerow([
                "Date & Time", "Source", "Systolic BP (mmHg)", "Diastolic BP (mmHg)",
                "Heart Rate (bpm)", "Blood Glucose (mg/dL)", "BMI", "SpO2 (%)",
                "Temp (C)", "Resp Rate", "Weight (kg)",
                "Diabetes Risk", "Hypertension Risk", "Stroke Risk", "Notes",
            ])
            for r in rows:
                w.writerow([
                    r["recorded_at"].strftime("%Y-%m-%d %H:%M"),
                    r["source"], r["sys"], r["dia"], r["hr"], r["glu"], r["bmi"],
                    r["spo2"], r["temp"], r["rr"], r["weight"],
                    risk_cell(r["diabetes"].risk_level, r["diabetes"].risk_score) if r["diabetes"] else "-",
                    risk_cell(r["hypertension"].risk_level, r["hypertension"].risk_score) if r["hypertension"] else "-",
                    risk_cell(r["stroke"].risk_level, r["stroke"].risk_score) if r["stroke"] else "-",
                    r["notes"],
                ])

        md_path = out_dir / "demo_vitals_history.md"
        with open(md_path, "w", encoding="utf-8") as f:
            f.write(f"# Demo Vitals History — Yussif Hamza\n\n")
            f.write(f"Patient: Yussif Hamza (male, 56) | Primary condition: Stroke\n")
            f.write(f"Total readings: {len(rows)} | Period: {rows[-1]['recorded_at'].strftime('%Y-%m-%d')} → {rows[0]['recorded_at'].strftime('%Y-%m-%d')}\n\n")
            f.write("## Risk story\n\n")
            f.write("| Phase | Reading(s) | Vitals pattern | Diabetes | Hypertension | Stroke |\n")
            f.write("|---|---|---|---|---|---|---|\n")
            f.write("| **1 — Low** | 1–3 | Normal BP/glucose, weight stable | LOW | LOW | HIGH (chronic profile) |\n")
            f.write("| **2 — Moderate** | 4–8 | Glucose 128→146, BP 128/81→138/88, BMI 25.2→26.0 | LOW→MODERATE | MODERATE | HIGH |\n")
            f.write("| **3 — High** | 9–12 | Sustained BP ≥148/92, glucose 188→204 | HIGH | CRITICAL | CRITICAL |\n")
            f.write("| **4 — Critical** | 13–14 | Severe 176/108, glucose 250, HR 92 | CRITICAL | CRITICAL | CRITICAL |\n")
            f.write("| **5 — Recovery** | 15–18 | Post-intervention: BP/glucose fall, weight drops | HIGH→MODERATE | MODERATE | HIGH |\n\n")
            f.write("## Readings\n\n")
            f.write("| Date & Time | Source | Systolic | Diastolic | HR | Glucose | BMI | SpO2 | Weight | Diabetes | Hypertension | Stroke | Notes |\n")
            f.write("|---|---|---|---|---|---|---|---|---|---|---|---|---|\n")
            for r in rows:
                f.write(
                    f"| {r['recorded_at'].strftime('%Y-%m-%d %H:%M')} | {r['source']} "
                    f"| {r['sys']} | {r['dia']} | {r['hr']} | {r['glu']:.0f} | {r['bmi']:.1f} | {r['spo2']:.0f} | {r['weight']:.1f} "
                    f"| {risk_cell(r['diabetes'].risk_level, r['diabetes'].risk_score) if r['diabetes'] else '-'} "
                    f"| {risk_cell(r['hypertension'].risk_level, r['hypertension'].risk_score) if r['hypertension'] else '-'} "
                    f"| {risk_cell(r['stroke'].risk_level, r['stroke'].risk_score) if r['stroke'] else '-'} "
                    f"| {r['notes']} |\n"
                )

        print(f"\nWrote {csv_path}")
        print(f"Wrote {md_path}")
        print(f"Readings: {len(rows)} | Predictions: {db.query(RiskPrediction).count()}")
    finally:
        db.close()


if __name__ == "__main__":
    main()